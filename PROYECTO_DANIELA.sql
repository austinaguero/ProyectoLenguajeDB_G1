CREATE OR REPLACE PROCEDURE sp_listar_usuarios (
  p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN p_cursor FOR
    SELECT u.id_usuario,
           u.id_empleado,
           e.nombre || ' ' || e.primer_apellido AS nombre_completo,
           u.username,
           u.estado
    FROM usuarios u
    JOIN empleados e ON u.id_empleado = e.id_empleado
    ORDER BY u.username;
END sp_listar_usuarios;
/

CREATE OR REPLACE PROCEDURE sp_eliminar_usuario (
  p_id_usuario IN NUMBER
) AS
BEGIN
  DELETE FROM usuarios
  WHERE id_usuario = p_id_usuario;
  COMMIT;
END sp_eliminar_usuario;
/

CREATE OR REPLACE PROCEDURE sp_listar_facturas (
  p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN p_cursor FOR
    SELECT f.id_factura,
           f.numero_factura,
           f.fecha_emision,
           c.nombre_cliente,
           u.username,
           m.nombre_metodo,
           f.subtotal,
           f.impuesto,
           f.monto_total,
           f.estado
    FROM facturas f
    JOIN clientes c ON f.id_cliente = c.id_cliente
    JOIN usuarios u ON f.id_usuario = u.id_usuario
    JOIN metodos_pago m ON f.id_metodo_pago = m.id_metodo_pago
    ORDER BY f.fecha_emision DESC;
END sp_listar_facturas;
