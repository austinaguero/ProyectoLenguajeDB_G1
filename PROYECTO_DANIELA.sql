CREATE OR REPLACE PROCEDURE sp_insertar_empleado (
  p_cedula IN VARCHAR2,
  p_nombre IN VARCHAR2,
  p_primer_apellido IN VARCHAR2,
  p_segundo_apellido IN VARCHAR2,
  p_correo IN VARCHAR2,
  p_telefono IN VARCHAR2
) AS
BEGIN
  INSERT INTO empleados (cedula, nombre, primer_apellido, segundo_apellido, correo, telefono)
  VALUES (p_cedula, p_nombre, p_primer_apellido, p_segundo_apellido, p_correo, p_telefono);
  COMMIT;
END sp_insertar_empleado;
/

CREATE OR REPLACE PROCEDURE sp_actualizar_empleado (
  p_id_empleado IN NUMBER,
  p_cedula IN VARCHAR2,
  p_nombre IN VARCHAR2,
  p_primer_apellido IN VARCHAR2,
  p_segundo_apellido IN VARCHAR2,
  p_correo IN VARCHAR2,
  p_telefono IN VARCHAR2
) AS
BEGIN
  UPDATE empleados
  SET cedula = p_cedula,
      nombre = p_nombre,
      primer_apellido = p_primer_apellido,
      segundo_apellido = p_segundo_apellido,
      correo = p_correo,
      telefono = p_telefono
  WHERE id_empleado = p_id_empleado;
  COMMIT;
END sp_actualizar_empleado;
/

CREATE OR REPLACE PROCEDURE sp_eliminar_empleado (
  p_id_empleado IN NUMBER
) AS
BEGIN
  DELETE FROM empleados
  WHERE id_empleado = p_id_empleado;
  COMMIT;
END sp_eliminar_empleado;
/

CREATE OR REPLACE PROCEDURE sp_listar_empleados (
  p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN p_cursor FOR
    SELECT id_empleado, cedula, nombre, primer_apellido, segundo_apellido, correo, telefono
    FROM empleados
    ORDER BY primer_apellido, nombre;
END sp_listar_empleados;
/

