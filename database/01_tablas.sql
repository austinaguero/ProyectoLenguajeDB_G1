BEGIN
  FOR t IN (
    SELECT table_name
    FROM user_tables
    WHERE table_name IN (
      'DETALLE_FACTURA',
      'FACTURAS',
      'METODOS_PAGO',
      'CLIENTES',
      'MOVIMIENTOS_INVENTARIO',
      'PRODUCTOS',
      'PROVEEDORES',
      'CATEGORIAS',
      'USUARIO_ROL',
      'USUARIOS',
      'ROLES',
      'EMPLEADOS'
    )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE empleados (
  id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cedula VARCHAR2(20) NOT NULL,
  nombre VARCHAR2(50) NOT NULL,
  primer_apellido VARCHAR2(50) NOT NULL,
  segundo_apellido VARCHAR2(50),
  correo VARCHAR2(100),
  telefono VARCHAR2(20),
  CONSTRAINT pk_empleados PRIMARY KEY (id_empleado),
  CONSTRAINT uq_empleados_cedula UNIQUE (cedula),
  CONSTRAINT ck_empleados_correo CHECK (correo IS NULL OR correo LIKE '%_@_%._%')
);

CREATE TABLE roles (
  id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre_rol VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_roles PRIMARY KEY (id_rol),
  CONSTRAINT uq_roles_nombre UNIQUE (nombre_rol)
);

CREATE TABLE usuarios (
  id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empleado NUMBER NOT NULL,
  username VARCHAR2(50) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuarios_username UNIQUE (username),
  CONSTRAINT uq_usuarios_empleado UNIQUE (id_empleado),
  CONSTRAINT fk_usuarios_empleado FOREIGN KEY (id_empleado) REFERENCES empleados (id_empleado),
  CONSTRAINT ck_usuarios_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE usuario_rol (
  id_usuario NUMBER NOT NULL,
  id_rol NUMBER NOT NULL,
  CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol),
  CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
  CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol) REFERENCES roles (id_rol)
);

CREATE TABLE categorias (
  id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre_categoria VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_categorias PRIMARY KEY (id_categoria),
  CONSTRAINT uq_categorias_nombre UNIQUE (nombre_categoria)
);

CREATE TABLE proveedores (
  id_proveedor NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cedula_juridica VARCHAR2(20) NOT NULL,
  nombre_proveedor VARCHAR2(150) NOT NULL,
  telefono VARCHAR2(20),
  correo VARCHAR2(100),
  direccion VARCHAR2(255),
  CONSTRAINT pk_proveedores PRIMARY KEY (id_proveedor),
  CONSTRAINT uq_proveedores_cedula UNIQUE (cedula_juridica),
  CONSTRAINT ck_proveedores_correo CHECK (correo IS NULL OR correo LIKE '%_@_%._%')
);

CREATE TABLE productos (
  id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo_producto VARCHAR2(30) NOT NULL,
  nombre_producto VARCHAR2(150) NOT NULL,
  id_categoria NUMBER NOT NULL,
  id_proveedor NUMBER NOT NULL,
  precio_venta NUMBER(12,2) NOT NULL,
  stock_actual NUMBER(10) DEFAULT 0 NOT NULL,
  stock_minimo NUMBER(10) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_productos PRIMARY KEY (id_producto),
  CONSTRAINT uq_productos_codigo UNIQUE (codigo_producto),
  CONSTRAINT fk_productos_categoria FOREIGN KEY (id_categoria) REFERENCES categorias (id_categoria),
  CONSTRAINT fk_productos_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedores (id_proveedor),
  CONSTRAINT ck_productos_precio CHECK (precio_venta > 0),
  CONSTRAINT ck_productos_stock CHECK (stock_actual >= 0),
  CONSTRAINT ck_productos_stock_min CHECK (stock_minimo >= 0)
);

CREATE TABLE movimientos_inventario (
  id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_producto NUMBER NOT NULL,
  id_usuario NUMBER NOT NULL,
  tipo_movimiento VARCHAR2(10) NOT NULL,
  cantidad NUMBER(10) NOT NULL,
  fecha_movimiento TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  motivo VARCHAR2(255),
  CONSTRAINT pk_movimientos PRIMARY KEY (id_movimiento),
  CONSTRAINT fk_movimientos_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
  CONSTRAINT fk_movimientos_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario),
  CONSTRAINT ck_movimientos_tipo CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA')),
  CONSTRAINT ck_movimientos_cantidad CHECK (cantidad > 0)
);

CREATE TABLE clientes (
  id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY,
  identificacion VARCHAR2(20) NOT NULL,
  nombre_cliente VARCHAR2(150) NOT NULL,
  telefono VARCHAR2(20),
  correo VARCHAR2(100),
  direccion VARCHAR2(255),
  CONSTRAINT pk_clientes PRIMARY KEY (id_cliente),
  CONSTRAINT uq_clientes_identificacion UNIQUE (identificacion),
  CONSTRAINT ck_clientes_correo CHECK (correo IS NULL OR correo LIKE '%_@_%._%')
);

CREATE TABLE metodos_pago (
  id_metodo_pago NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre_metodo VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_metodos_pago PRIMARY KEY (id_metodo_pago),
  CONSTRAINT uq_metodos_pago_nombre UNIQUE (nombre_metodo)
);

CREATE TABLE facturas (
  id_factura NUMBER GENERATED BY DEFAULT AS IDENTITY,
  numero_factura VARCHAR2(30) NOT NULL,
  fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  id_cliente NUMBER NOT NULL,
  id_usuario NUMBER NOT NULL,
  id_metodo_pago NUMBER NOT NULL,
  subtotal NUMBER(12,2) DEFAULT 0 NOT NULL,
  impuesto NUMBER(12,2) DEFAULT 0 NOT NULL,
  monto_total NUMBER(12,2) DEFAULT 0 NOT NULL,
  estado VARCHAR2(10) DEFAULT 'EMITIDA' NOT NULL,
  CONSTRAINT pk_facturas PRIMARY KEY (id_factura),
  CONSTRAINT uq_facturas_numero UNIQUE (numero_factura),
  CONSTRAINT fk_facturas_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente),
  CONSTRAINT fk_facturas_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario),
  CONSTRAINT fk_facturas_metodo FOREIGN KEY (id_metodo_pago) REFERENCES metodos_pago (id_metodo_pago),
  CONSTRAINT ck_facturas_subtotal CHECK (subtotal >= 0),
  CONSTRAINT ck_facturas_impuesto CHECK (impuesto >= 0),
  CONSTRAINT ck_facturas_total CHECK (monto_total >= 0),
  CONSTRAINT ck_facturas_estado CHECK (estado IN ('EMITIDA', 'ANULADA'))
);

CREATE TABLE detalle_factura (
  id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_factura NUMBER NOT NULL,
  id_producto NUMBER NOT NULL,
  cantidad NUMBER(10) NOT NULL,
  precio_unitario NUMBER(12,2) NOT NULL,
  subtotal_linea NUMBER(12,2) NOT NULL,
  CONSTRAINT pk_detalle_factura PRIMARY KEY (id_detalle),
  CONSTRAINT uq_detalle_producto UNIQUE (id_factura, id_producto),
  CONSTRAINT fk_detalle_factura FOREIGN KEY (id_factura) REFERENCES facturas (id_factura) ON DELETE CASCADE,
  CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
  CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_precio CHECK (precio_unitario > 0),
  CONSTRAINT ck_detalle_subtotal CHECK (subtotal_linea > 0)
);

CREATE INDEX ix_usuario_rol_rol ON usuario_rol (id_rol);
CREATE INDEX ix_productos_categoria ON productos (id_categoria);
CREATE INDEX ix_productos_proveedor ON productos (id_proveedor);
CREATE INDEX ix_movimientos_producto ON movimientos_inventario (id_producto);
CREATE INDEX ix_movimientos_usuario ON movimientos_inventario (id_usuario);
CREATE INDEX ix_movimientos_fecha ON movimientos_inventario (fecha_movimiento);
CREATE INDEX ix_facturas_cliente ON facturas (id_cliente);
CREATE INDEX ix_facturas_usuario ON facturas (id_usuario);
CREATE INDEX ix_facturas_metodo ON facturas (id_metodo_pago);
CREATE INDEX ix_facturas_fecha ON facturas (fecha_emision);
CREATE INDEX ix_detalle_producto ON detalle_factura (id_producto);

SELECT table_name
FROM user_tables
WHERE table_name IN (
  'EMPLEADOS',
  'ROLES',
  'USUARIOS',
  'USUARIO_ROL',
  'CATEGORIAS',
  'PROVEEDORES',
  'PRODUCTOS',
  'MOVIMIENTOS_INVENTARIO',
  'CLIENTES',
  'METODOS_PAGO',
  'FACTURAS',
  'DETALLE_FACTURA'
)
ORDER BY table_name;